import assert from "node:assert/strict";
import fs from "node:fs/promises";
import {chromium} from "playwright";

const ROOT="http://127.0.0.1:8077";
await fs.mkdir("artifacts/browser", {recursive:true});
const browser=await chromium.launch({headless:true});
const errors=[];
const pass=(message)=>console.log("PASS:",message);

try {
  const desktop=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
  desktop.on("pageerror",e=>errors.push("Desktop pageerror: "+e.message));
  desktop.on("console",m=>{if(m.type()==="error")errors.push("Desktop console: "+m.text());});
  const response=await desktop.goto(ROOT,{waitUntil:"networkidle",timeout:30000});
  assert.equal(response.status(),200);
  await desktop.locator(".setting").first().waitFor({state:"visible"});
  assert.equal(await desktop.locator(".setting").count(),7);
  assert.equal(await desktop.locator(".readout").count(),7);
  assert.equal(await desktop.locator("#panel-circuit").isVisible(),true);
  pass("desktop loads all 7 settings and 7 reference readouts");

  const monitorBefore=await desktop.locator("#monitor").innerText();
  const oxygenUp=desktop.getByRole("button",{name:"O₂ 증가 10"});
  await oxygenUp.click();
  assert.equal(await desktop.locator(".setting-value").first().innerText(),"50");
  assert.equal(await oxygenUp.evaluate(el=>document.activeElement===el),true,"keyboard focus lost");
  await oxygenUp.press("Enter");
  assert.equal(await desktop.locator(".setting-value").first().innerText(),"60");
  assert.equal(await desktop.locator("#monitor").innerText(),monitorBefore);
  pass("FiO₂ mouse/keyboard adjustment preserves focus and does not change example monitor");
  await desktop.getByRole("button",{name:"O₂ 설명 보기"}).click();
  assert.equal(await desktop.locator("#panel-help").isVisible(),true);
  assert.equal(await desktop.locator("#help-title").innerText(),"O₂");
  pass("setting help opens on right");
  await desktop.getByRole("tab",{name:"CIRCUIT"}).click();
  await desktop.getByRole("button",{name:"조립 개요"}).click();
  assert.match(await desktop.locator("#circuit-content").innerText(),/1\/4/);
  await desktop.getByRole("button",{name:"다음 →"}).click();
  assert.match(await desktop.locator("#circuit-content").innerText(),/2\/4/);
  await desktop.getByRole("button",{name:"완성 개념도"}).click();
  assert.equal(await desktop.locator("#circuit-content svg").count(),1);
  pass("CIRCUIT subtabs, assembly steps and schematic");
  await desktop.getByRole("button",{name:"설정 초기화"}).click();
  assert.equal(await desktop.locator(".setting-value").first().innerText(),"40");
  pass("reset restores initial settings");
  // v0.3: the three phase-colored waveform panels are interactive teaching previews.
  assert.equal(await desktop.locator(".waveform-svg").count(),3);
  const pPath=desktop.locator('#graph-pressure [data-phase="mandatory"]');
  const flowPath=desktop.locator('#graph-flow [data-phase="expiration"]');
  const volPath=desktop.locator('#graph-volume [data-phase="mandatory"]');
  assert.ok((await pPath.getAttribute("d")).length>20);
  assert.ok((await flowPath.getAttribute("d")).length>20);
  assert.ok((await volPath.getAttribute("d")).length>20);
  await desktop.getByRole("button",{name:"파형 일시정지"}).click();
  const pausedPath=await pPath.getAttribute("d");
  await desktop.waitForTimeout(260);
  assert.equal(await pPath.getAttribute("d"),pausedPath,"paused waveform should not scroll");
  await desktop.getByRole("button",{name:"Pᵢ 증가 1"}).click();
  const higherPi=await pPath.getAttribute("d");
  assert.notEqual(higherPi,pausedPath,"Pi should update mandatory waveform");
  const beforePS=await desktop.locator('#graph-pressure [data-phase="spontaneous"]').getAttribute("d");
  await desktop.getByRole("button",{name:"PS 증가 1"}).click();
  assert.notEqual(await desktop.locator('#graph-pressure [data-phase="spontaneous"]').getAttribute("d"),beforePS);
  await desktop.getByRole("button",{name:"PEEP 증가 1"}).click();
  assert.notEqual(await pPath.getAttribute("d"),higherPi);
  await desktop.getByRole("button",{name:"파형 재생"}).click();
  const playingBefore=await pPath.getAttribute("d");
  await desktop.waitForTimeout(280);
  assert.notEqual(await pPath.getAttribute("d"),playingBefore,"waveform should scroll while playing");
  pass("three phase-colored graphs, Pi/PS/PEEP response, pause and resume");
  await desktop.getByRole("button",{name:"설정 초기화"}).click();
  assert.equal(await desktop.locator(".setting-value").first().innerText(),"40");
  pass("v0.3 controls reset without disrupting waveforms");
  await desktop.screenshot({path:"artifacts/browser/desktop.png",fullPage:true});

  const mobile=await browser.newPage({viewport:{width:360,height:780},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on("pageerror",e=>errors.push("Mobile pageerror: "+e.message));
  mobile.on("console",m=>{if(m.type()==="error")errors.push("Mobile console: "+m.text());});
  const mobileResponse=await mobile.goto(ROOT,{waitUntil:"networkidle",timeout:30000});
  assert.equal(mobileResponse.status(),200);
  await mobile.locator(".setting").first().waitFor({state:"visible"});
  assert.equal(await mobile.locator(".setting").count(),7);
  const width=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  assert.ok(width.scroll<=width.client+2,"mobile horizontal overflow "+JSON.stringify(width));
  await mobile.getByRole("button",{name:"PEEP 증가 0.1"}).click();
  const peepVal=await mobile.locator(".setting").nth(1).locator(".setting-value").innerText();
  assert.equal(peepVal,"5.1");
  await mobile.getByRole("tab",{name:"? 설명"}).click();
  assert.equal(await mobile.locator("#panel-help").isVisible(),true);
  pass("360px mobile layout, step control and help tab");
  assert.equal(await mobile.locator(".waveform-svg").count(),3);
  await mobile.screenshot({path:"artifacts/browser/mobile.png",fullPage:true});

  const narrow=await browser.newPage({viewport:{width:320,height:680},isMobile:true,hasTouch:true});
  narrow.on("pageerror",e=>errors.push("320px page error: "+e.message));
  const narrowResponse=await narrow.goto(ROOT,{waitUntil:"networkidle",timeout:30000});
  assert.equal(narrowResponse.status(),200);
  await narrow.locator(".setting").first().waitFor({state:"visible"});
  const narrowSize=await narrow.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  assert.ok(narrowSize.scroll<=narrowSize.client+2,"320px horizontal overflow "+JSON.stringify(narrowSize));
  await narrow.getByRole("button",{name:"O₂ 증가 10"}).click();
  assert.equal(await narrow.locator(".setting-value").first().innerText(),"50");
  pass("320px mobile width: no horizontal overflow, settings interactive");
  await narrow.screenshot({path:"artifacts/browser/narrow-320.png",fullPage:true});
  assert.deepEqual(errors,[]);
  pass("no captured JS page errors or console errors");
} finally {
  await browser.close();
}
